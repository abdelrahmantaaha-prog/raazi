# Builds Raazi.exe.
#
#   powershell -ExecutionPolicy Bypass -File launcher\build.ps1
#
# Uses the C# compiler that ships with Windows (.NET Framework 4), so there is
# nothing to install. Produces a ~15 KB exe in the project root, plus an icon
# and a desktop shortcut.

#   -Out <path>        build there instead of the project root
#   -NoShortcut        leave the desktop shortcut alone
#   -Test              the test build: plain-HTTP feeds on loopback, a port of its own
#   -KeysFile <path>   trust the keys in that file instead of launcher\UpdateKeys.cs (tests)
param(
  [string]$Out = "",
  [switch]$NoShortcut,
  [switch]$Test,
  [string]$KeysFile = ""
)

$ErrorActionPreference = "Stop"

$root = Split-Path -Parent $PSScriptRoot
$csc  = Join-Path $env:WINDIR "Microsoft.NET\Framework64\v4.0.30319\csc.exe"
if (-not (Test-Path $csc)) {
  $csc = Join-Path $env:WINDIR "Microsoft.NET\Framework\v4.0.30319\csc.exe"
}
if (-not (Test-Path $csc)) {
  throw "No C# compiler found. Install the .NET Framework 4 developer pack, or use Raazi.bat instead."
}

# --- icon -------------------------------------------------------------------
# A serif R on a warm ground, matching the app. Drawn rather than shipped as a
# binary so there is no opaque blob in the repo.
Add-Type -AssemblyName System.Drawing

$icoPath = Join-Path $PSScriptRoot "corpus.ico"
$sizes   = 256, 64, 48, 32, 16
$pngs    = @()

foreach ($size in $sizes) {
  $bmp = New-Object System.Drawing.Bitmap $size, $size
  $g   = [System.Drawing.Graphics]::FromImage($bmp)
  $g.SmoothingMode     = [System.Drawing.Drawing2D.SmoothingMode]::AntiAlias
  $g.TextRenderingHint = [System.Drawing.Text.TextRenderingHint]::AntiAliasGridFit

  $bg = New-Object System.Drawing.SolidBrush ([System.Drawing.Color]::FromArgb(122, 75, 42))
  $g.FillEllipse($bg, 0, 0, ($size - 1), ($size - 1))

  $fg     = New-Object System.Drawing.SolidBrush ([System.Drawing.Color]::FromArgb(251, 250, 247))
  $font   = New-Object System.Drawing.Font "Georgia", ($size * 0.58), ([System.Drawing.FontStyle]::Bold), ([System.Drawing.GraphicsUnit]::Pixel)
  $format = New-Object System.Drawing.StringFormat
  $format.Alignment     = [System.Drawing.StringAlignment]::Center
  $format.LineAlignment = [System.Drawing.StringAlignment]::Center
  $rect = New-Object System.Drawing.RectangleF 0, ($size * 0.02), $size, $size
  $g.DrawString("R", $font, $fg, $rect, $format)

  $g.Dispose()

  $stream = New-Object System.IO.MemoryStream
  $bmp.Save($stream, [System.Drawing.Imaging.ImageFormat]::Png)
  $pngs += ,($stream.ToArray())
  $bmp.Dispose()
  $stream.Dispose()
}

# ICO container: 6-byte header, then a 16-byte directory entry per image.
$ico = New-Object System.IO.MemoryStream
$w   = New-Object System.IO.BinaryWriter $ico
$w.Write([UInt16]0); $w.Write([UInt16]1); $w.Write([UInt16]$sizes.Count)

$offset = 6 + (16 * $sizes.Count)
for ($i = 0; $i -lt $sizes.Count; $i++) {
  $dim = if ($sizes[$i] -ge 256) { 0 } else { $sizes[$i] }
  $w.Write([Byte]$dim); $w.Write([Byte]$dim)
  $w.Write([Byte]0); $w.Write([Byte]0)
  $w.Write([UInt16]1); $w.Write([UInt16]32)
  $w.Write([UInt32]$pngs[$i].Length)
  $w.Write([UInt32]$offset)
  $offset += $pngs[$i].Length
}
foreach ($png in $pngs) { $w.Write($png) }
$w.Flush()
[System.IO.File]::WriteAllBytes($icoPath, $ico.ToArray())
$w.Dispose(); $ico.Dispose()
Write-Host "icon    -> $icoPath"

# --- compile ----------------------------------------------------------------
$exe = if ($Out) { $Out } else { Join-Path $root "Raazi.exe" }
$src = Join-Path $PSScriptRoot "Launcher.cs"

$swapSrc = Join-Path $PSScriptRoot "UpdateSwap.cs"
$feedSrc = Join-Path $PSScriptRoot "UpdateFeed.cs"
$awakeSrc = Join-Path $PSScriptRoot "Awake.cs"
$keysSrc = if ($KeysFile) { $KeysFile } else { Join-Path $PSScriptRoot "UpdateKeys.cs" }

# The release this exe belongs to, from package.json; a new starter answers
# --selftest with it before it is allowed to replace the old one.
$version = (Get-Content (Join-Path $root "package.json") -Raw | ConvertFrom-Json).version
$verSrc  = Join-Path $PSScriptRoot "Version.cs"
@"
// Generated by launcher/build.ps1 from package.json. Do not edit.
static class Build { public const string Release = "$version"; }
"@ | Set-Content -Path $verSrc -Encoding ASCII
Write-Host "version -> $version"

$defines = if ($Test) { "/define:UPDATE_TESTS" } else { "/define:RELEASE" }
& $csc /nologo /target:winexe /optimize+ /codepage:65001 $defines /out:"$exe" `
  /win32icon:"$icoPath" `
  /reference:System.dll `
  /reference:System.Drawing.dll `
  /reference:System.Windows.Forms.dll `
  /reference:System.IO.Compression.dll `
  /reference:System.IO.Compression.FileSystem.dll `
  "$src" "$swapSrc" "$feedSrc" "$awakeSrc" "$keysSrc" "$verSrc"

if ($LASTEXITCODE -ne 0) { throw "Compilation failed." }
Write-Host "exe     -> $exe"

# --- desktop shortcut -------------------------------------------------------
if ($NoShortcut) { Write-Host "shortcut-> skipped (-NoShortcut)" }
else { try {
  $desktop  = [Environment]::GetFolderPath("Desktop")
  $lnk      = Join-Path $desktop "Raazi.lnk"
  $shell    = New-Object -ComObject WScript.Shell
  $shortcut = $shell.CreateShortcut($lnk)
  $shortcut.TargetPath       = $exe
  $shortcut.WorkingDirectory = $root
  $shortcut.IconLocation     = $icoPath
  $shortcut.Description      = "Raazi - your research pedia"
  $shortcut.Save()
  Write-Host "shortcut-> $lnk"
  # The shortcut from before the rename to Raazi points at a Corpus.exe that
  # is no longer built.
  $old = Join-Path $desktop "Corpus.lnk"
  if (Test-Path $old) { Remove-Item $old -Force; Write-Host "removed -> $old" }
} catch {
  Write-Host "shortcut-> skipped ($($_.Exception.Message))"
} }

Write-Host ""
Write-Host "Done. Double-click Raazi.exe (or the desktop shortcut) to start."
